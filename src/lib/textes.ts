export type CleTexte = keyof typeof textesFrancais;
export type LangueInterface = "fr" | "ar";

export function getLangueInterface(): LangueInterface {
  if (typeof window === "undefined") return "fr";
  const locale = window.localStorage.getItem("gym4you-language");
  return locale === "ar" ? "ar" : "fr";
}

export function appliquerLangueInterface(langue: LangueInterface): void {
  if (typeof document !== "undefined") {
    document.documentElement.lang = langue === "ar" ? "ar" : "fr";
    document.documentElement.dir = langue === "ar" ? "rtl" : "ltr";
  }
  if (typeof window !== "undefined") {
    window.localStorage.setItem("gym4you-language", langue);
  }
}

